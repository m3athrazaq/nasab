export function demoState() {
  const id = k => 'demo' + k;
  const people = {}, unions = {};
  const couple = new Map();
  const unionFor = (f, m) => {
    const key = f + '|' + m;
    if (!couple.has(key)) {
      const uid = 'demou' + couple.size;
      couple.set(key, uid);
      unions[uid] = { id: uid, h: f ? id(f) : '', w: m ? id(m) : '', st: 'm', md: '' };
    }
    return couple.get(key);
  };
  for (const [h, wv, md] of MARRIED) { const u = unionFor(h, wv); if (md) unions[u].md = md; }
  let at = 1700000000000;
  for (const [k, n, g, b, d, f, m, extra] of P) {
    people[id(k)] = { id: id(k), n, g, b, d: d === '-' ? '' : d, dead: !!d, pu: f || m ? unionFor(f, m) : '', at: at++, ...extra };
  }
  return { people, unions, me: id('k4'), root: id('r1') };
}
